/* Оценка организации модулей по связям между ними

    Модуль может входит в семейство модулей и также интегрировать поведение других модулей для решения поставленной задачи. 
    Поэтому публичыне связи между модулями ожидаемы и используются часто, через публичные методы, внедрение различных зависимостей, переопределение метовод наследниками...

    На первый взгляд кажется что можно оценить организацию модулей по количеству входящих зависимостей и исходящих связей-ссылок на модуль.

        - Числов зависимостей, которые использует модуль: Если модуль зависит от большого числа других модулей то он сам зависит от точности других модулей и ошибок в них, кажется чем меньше подобных зависимостей тем лучше. 

        - Число других модулей, которые используют текущий модуль: Если от модуля зависит большое число других модулей то его изменения будут каждый раз иметь большое влияние и затрагивать большое количество потребителей. 
    В этом случае изменения должны быть как можно более точными и протестированы тк цена ошибки будет высокой. В идеале такой модуль должен очень редко меняться.

            Также когда это число высокое это показатель что модуль имеет слишком много ответственности и является кандидатом на рефакторинг.

*/

